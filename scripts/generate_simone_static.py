#!/usr/bin/env python3
"""Generate the reviewed static Python RHS for the pinned Simone model.

This is a build-time translator. The generated module is committed and imported
normally by production; no model source is executed or translated at runtime.
"""
from __future__ import annotations

import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "model_assets/ventricular/simone/Simone_Trancuccio2025.m"
MAIN = ROOT / "model_assets/ventricular/simone/Main_Simone_Trancuccio_2025.m"
TARGET = ROOT / "backend/app/backends/simone_static_rhs.py"


def strip_comment(line: str) -> str:
    return line.split("%", 1)[0].rstrip()


def statement(line: str) -> str:
    line = strip_comment(line).strip()
    if not line:
        return ""
    for name in ("exp", "log", "sqrt", "floor"):
        line = re.sub(rf"\b{name}\(", f"np.{name}(", line)
    line = line.replace("^", "**").replace(".*", "*").replace("./", "/")
    line = line.replace("~=", "!=").replace("&&", " and ").replace("||", " or ")
    line = re.sub(r"Y\((\d+)\)", lambda m: f"y[{int(m.group(1)) - 1}]", line)
    line = re.sub(r"dY\((\d+),\s*1\)", lambda m: f"dy[{int(m.group(1)) - 1}]", line)
    line = re.sub(r"\bdY\b", "dy", line).rstrip(";")
    if line.startswith("error("):
        return "raise ValueError" + line[len("error"):]
    if line.startswith("disp("):
        return "print" + line[len("disp"):]
    return line


def main() -> None:
    source = re.sub(r"\.\.\.\s*\n\s*", " ", SOURCE.read_text(encoding="utf-8"))
    lines: list[str] = []
    indent = 1
    for raw in source.splitlines():
        line = strip_comment(raw).strip()
        if not line or line.startswith("function "):
            continue
        if line == "else":
            indent -= 1
            lines.append("    " * indent + "else:")
            indent += 1
            continue
        if line == "end":
            indent -= 1
            continue
        if line.startswith("if "):
            lines.append("    " * indent + f"if {statement(line[3:])}:")
            indent += 1
            continue
        transformed = statement(line)
        if transformed:
            lines.append("    " * indent + transformed)

    replacements = {
        r"^i_stim_Amplitude": "    i_stim_Amplitude = stim_amplitude_A",
        r"^i_stim_End": "    i_stim_End = stim_end_s",
        r"^i_stim_PulseDuration": "    i_stim_PulseDuration = stim_duration_s",
        r"^i_stim_Start": "    i_stim_Start = stim_offset_s",
        r"^g_Na\s*=": "    g_Na = params.get('g_Na', 1.2176 * 6447.1896)",
        r"^GNaLmax\s*=": "    GNaLmax = params.get('GNaLmax', 1.3021 * 2.3 * 7.5)",
        r"^bGCaL\s*=": "    bGCaL = params.get('bGCaL', 1.0)",
        r"^g_f\s*=": "    g_f = params.get('g_f', 0.62395 * 22.2763088)",
        r"^g_to\s*=": "    g_to = params.get('g_to', 1.2913 * 29.9038)",
        r"^g_Ks\s*=": "    g_Ks = params.get('g_Ks', 1.0726 * 2.041)",
        r"^g_Kr\s*=": "    g_Kr = params.get('g_Kr', 1.9913 * 29.8667)",
        r"^g_K1\s*=": "    g_K1 = params.get('g_K1', 0.50122 * 28.1492)",
        r"^kNaCa\s*=": "    kNaCa = params.get('kNaCa', 0.66821 * 6514.47574)",
        r"^PNaK\s*=": "    PNaK = params.get('PNaK', 1.3055 * 2.74240)",
    }
    for index, line in enumerate(lines):
        stripped = line.strip()
        for pattern, replacement in replacements.items():
            if re.match(pattern, stripped):
                lines[index] = replacement
                break

    main_text = re.sub(r"\.\.\.\s*\n\s*", " ", MAIN.read_text(encoding="utf-8"))
    match = re.search(r"X0=\[(.*?)\];", main_text, re.S)
    if match is None:
        raise RuntimeError("Could not parse Simone initial conditions")
    initial = [float(token) for token in match.group(1).split()]
    if len(initial) != 37:
        raise RuntimeError(f"Expected 37 states, found {len(initial)}")

    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    header = [
        '"""Generated static port of the pinned Simone–Trancuccio 2025 RHS.',
        "",
        f"Source SHA-256: {digest}",
        "Generated by scripts/generate_simone_static.py; do not edit by hand.",
        '"""',
        "from __future__ import annotations",
        "",
        "import numpy as np",
        "",
        f"SOURCE_SHA256 = {digest!r}",
        f"INITIAL_STATE = np.asarray({initial!r}, dtype=float)",
        "",
        "def simone_rhs(time, y, stimFlag, odeflag, i_stim_frequency, fractional_TS,",
        "               stim_amplitude_A=5.5e-10, stim_duration_s=0.005,",
        "               stim_offset_s=0.0, stim_end_s=1000.0, params=None):",
        "    dy = np.zeros_like(y)",
        "    params = {} if params is None else params",
    ]
    TARGET.write_text("\n".join(header + lines + ["    return output", ""]) , encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(ROOT)} ({digest})")


if __name__ == "__main__":
    main()
